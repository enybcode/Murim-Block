function icon(h) {
  const img = new Uint8Array(16 * 16 * 4);
  h.rows.forEach((row, y) => {
    if (row.length !== 16) throw new Error('a row of ' + row.length);
    [...row].forEach((l, x) => {
      if (l === '.') return;
      const c = h.pal[l];
      if (!c) throw new Error('no colour ' + l);
      img.set([parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16), 255], (y * 16 + x) * 4);
    });
  });
  return kit.png(16, 16, img);
}

if (require.main === module) {
  const out = process.argv[2] || path.join(ASSETS, 'textures', 'item', 'herb');
  fs.mkdirSync(out, { recursive: true });
  for (const [name, h] of Object.entries(HERBS)) fs.writeFileSync(path.join(out, name + '.png'), icon(h));
  console.log('wrote', Object.keys(HERBS).length, 'herb icons to', out);
}
module.exports = { HERBS, icon };
