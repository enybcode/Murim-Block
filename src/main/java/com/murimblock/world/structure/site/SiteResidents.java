package com.murimblock.world.structure.site;

import com.mojang.logging.LogUtils;
import com.murimblock.Murimblock;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import net.minecraft.core.HolderLookup;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.StringTag;
import net.minecraft.nbt.Tag;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import net.minecraft.world.level.levelgen.structure.StructurePiece;
import net.minecraft.world.level.levelgen.structure.StructureStart;
import net.minecraft.world.level.saveddata.SavedData;
import net.minecraft.world.phys.AABB;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.tick.PlayerTickEvent;
import org.slf4j.Logger;

/**
 * The residents of Murim sites generated before they had any (a world older than the sensei, the bandits, the crab
 * men...). A site places its residents as its chunks are generated (Canvas.spawn), once; a site generated by an older
 * version stays empty. So the first time a player comes into a site, once all its chunks and their entities are loaded:
 * if none of the residents it should have is there, they are placed now, as the site would have placed them. Each site
 * is looked at once (saved here per world): residents killed afterwards do not come back, and a site that already had
 * its residents is only noted.
 */
@EventBusSubscriber(modid = Murimblock.MOD_ID)
public final class SiteResidents extends SavedData {
    private static final Logger LOGGER = LogUtils.getLogger();
    static final String NAME = "murimblock_site_residents";
    /** How often each player's surroundings are looked at (ticks). */
    static final int EVERY = 40;
    public static final SavedData.Factory<SiteResidents> FACTORY = new SavedData.Factory<>(SiteResidents::new, SiteResidents::load);

    /** The sites already looked at: their structure and the chunk of their start. */
    private final Set<String> settled = new HashSet<>();

    public static SiteResidents get(ServerLevel level) {
        return level.getDataStorage().computeIfAbsent(FACTORY, NAME);
    }

    @SubscribeEvent
    public static void onPlayerTick(PlayerTickEvent.Post event) {
        if (!(event.getEntity() instanceof ServerPlayer player) || player.tickCount % EVERY != 0) return;
        ServerLevel level = player.serverLevel();
        ChunkPos here = player.chunkPosition();
        for (StructureStart start : level.structureManager().startsForStructure(here, s -> s instanceof SiteStructure)) {
            if (!start.isValid()) continue;
            String key = key(start);
            SiteResidents data = get(level);
            if (data.settled.contains(key) || !entitiesLoaded(level, start.getBoundingBox())) continue;
            int placed = settle(level, pieces(start), start.getBoundingBox());
            if (placed > 0) LOGGER.info("Murim site {} at {}: placed its {} missing resident(s)", key, start.getBoundingBox().getCenter(), placed);
            data.settled.add(key);
            data.setDirty();
        }
    }

    /** Whether this site was already looked at (its residents placed, or found there). */
    public static boolean settled(ServerLevel level, StructureStart start) {
        return get(level).settled.contains(key(start));
    }

    private static String key(StructureStart start) {
        return start.getStructure() instanceof SiteStructure site ? site.plan().getSerializedName() + "@" + start.getChunkPos().toLong() : "?";
    }

    private static List<SitePiece> pieces(StructureStart start) {
        List<SitePiece> pieces = new ArrayList<>();
        for (StructurePiece p : start.getPieces()) if (p instanceof SitePiece site) pieces.add(site);
        return pieces;
    }

    /** Whether every chunk under the site is loaded with its entities (else a resident there would not be seen). */
    public static boolean entitiesLoaded(ServerLevel level, BoundingBox box) {
        for (int cx = box.minX() >> 4; cx <= box.maxX() >> 4; cx++)
            for (int cz = box.minZ() >> 4; cz <= box.maxZ() >> 4; cz++)
                if (!level.areEntitiesLoaded(ChunkPos.asLong(cx, cz))) return false;
        return true;
    }

    /**
     * Places the residents of these pieces if none of their kinds is in the site (its box, a little wider and down into
     * its pits); returns how many were placed.
     */
    public static int settle(ServerLevel level, List<SitePiece> pieces, BoundingBox box) {
        List<Canvas.Planned> planned = new ArrayList<>();
        for (SitePiece piece : pieces) planned.addAll(piece.residents());
        if (planned.isEmpty()) return 0;
        Set<EntityType<?>> kinds = new HashSet<>();
        for (Canvas.Planned p : planned) kinds.add(p.type());
        AABB area = AABB.of(box).inflate(4, 16, 4);
        if (!level.getEntitiesOfClass(Mob.class, area, m -> kinds.contains(m.getType())).isEmpty()) return 0;
        int placed = 0;
        for (Canvas.Planned p : planned) {
            @SuppressWarnings("unchecked") EntityType<Mob> type = (EntityType<Mob>) p.type();
            if (Canvas.place(level, type, p.at(), p.yaw(), p.setup()) != null) placed++;
        }
        return placed;
    }

    /** Tests: forgets that the sites around this block were looked at, as in a world older than their residents. */
    public static void forgetForTests(ServerLevel level, net.minecraft.core.BlockPos pos) {
        SiteResidents data = get(level);
        for (StructureStart start : level.structureManager().startsForStructure(new ChunkPos(pos), s -> s instanceof SiteStructure))
            data.settled.remove(key(start));
        data.setDirty();
    }

    // ---------------------------------------------------------------- saving

    @Override public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
        ListTag list = new ListTag();
        for (String key : settled) list.add(StringTag.valueOf(key));
        tag.put("settled", list);
        return tag;
    }

    private static SiteResidents load(CompoundTag tag, HolderLookup.Provider registries) {
        SiteResidents data = new SiteResidents();
        for (Tag t : tag.getList("settled", Tag.TAG_STRING)) data.settled.add(t.getAsString());
        return data;
    }
}
